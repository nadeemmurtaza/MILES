#!/usr/bin/env node
/* Builds public/i18n/ar.js from i18n-src/:
 *   ar-d.json  - the first Arabic dictionary (from the previous storefront, still valid for shared sentences)
 *   ar-g.json  - option G: { exact: { "<English>": "<Arabic>" }, patterns: [[regex, template]], page: { "G1-Home": { ... } } }
 * ar-g.json wins over ar-d.json. Patterns: "$1" is capture 1 (translated too), "@1[zero|one|two|few|many]" picks the
 * Arabic plural form for capture 1 and "#" is the number. Run: node scripts/build-i18n.mjs                         */
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n-src', f), 'utf8'));
const d = read('ar-d.json'), g = read('ar-g.json');
const out = { exact: { ...d.exact, ...g.exact }, patterns: [...(g.patterns || []), ...(d.patterns || [])], page: { ...d.page } };
for (const [pg, o] of Object.entries(g.page || {})) out.page[pg] = { ...(out.page[pg] || {}), ...o };
fs.mkdirSync(path.join(ROOT, 'public/i18n'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'public/i18n/ar.js'), '/* generated by scripts/build-i18n.mjs from i18n-src/ - do not edit */\nwindow.MILES_AR = ' + JSON.stringify(out) + ';\n');
console.log('public/i18n/ar.js:', Object.keys(out.exact).length, 'sentences,', out.patterns.length, 'patterns');
